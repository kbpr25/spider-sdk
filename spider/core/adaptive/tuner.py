# =============================================================================

class RestartStrategy:
    """
    Implements the Restart Strategy from Hypernetworks-2.
    
    "Periodically resetting learning rates to escape saddle points
    in rugged loss landscapes."
    
    When the solver plateaus (no improvement for N iterations),
    we "restart" by:
    1. Increasing temperature temporarily
    2. Resetting the MCTS tree
    3. Injecting exploration noise
    """
    
    def __init__(
        self,
        threshold: int = 10,
        temperature_boost: float = 0.3,
        exploration_boost: float = 0.5,
    ):
        self.threshold = threshold
        self.temperature_boost = temperature_boost
        self.exploration_boost = exploration_boost
        
        self.iterations_since_improvement = 0
        self.best_score = 0.0
        self.restart_count = 0
    
    def update(self, current_score: float) -> bool:
        """
        Update with current score and check if restart needed.
        
        Returns:
            True if a restart should be triggered
        """
        if current_score > self.best_score:
            self.best_score = current_score
            self.iterations_since_improvement = 0
            return False
        
        self.iterations_since_improvement += 1
        
        if self.iterations_since_improvement >= self.threshold:
            self.restart_count += 1
            self.iterations_since_improvement = 0
            logger.info(f"Restart triggered (count: {self.restart_count})")
            return True
        
        return False
    
    def apply_restart(self, config: SolverConfig) -> SolverConfig:
        """Apply restart modifications to config."""
        # Create modified config
        new_temp = min(1.0, config.temperature + self.temperature_boost)
        new_exploration = config.mcts_exploration + self.exploration_boost
        
        return SolverConfig(
            temperature=new_temp,
            top_p=config.top_p,
            max_tokens=config.max_tokens,
            mcts_iterations=config.mcts_iterations,
            mcts_exploration=new_exploration,
            mcts_rollout_depth=config.mcts_rollout_depth,
            z3_enabled=config.z3_enabled,
            z3_timeout_ms=config.z3_timeout_ms,
            test_enabled=config.test_enabled,
            test_timeout_s=config.test_timeout_s,
            max_iterations=config.max_iterations,
            error_threshold=config.error_threshold,
            restart_enabled=config.restart_enabled,
            restart_threshold=config.restart_threshold,
            source=f"restart:{self.restart_count}",
        )
    
    def reset(self) -> None:
        """Reset the strategy for a new task."""
        self.iterations_since_improvement = 0
        self.best_score = 0.0
        self.restart_count = 0


