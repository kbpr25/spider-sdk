@dataclass
class SolverConfig:
    """
    Dynamic solver configuration generated by the Hyper-Tuner.
    
    These are the "hyperparameters" of S.P.I.D.E.R. that adapt
    to each task type.
    """
    
    # LLM Parameters
    temperature: float = 0.5          # Creativity vs precision
    top_p: float = 0.95               # Nucleus sampling
    max_tokens: int = 2000            # Response length limit
    
    # MCTS Parameters  
    mcts_iterations: int = 50         # Search depth
    mcts_exploration: float = 1.414   # UCB1 exploration constant
    mcts_rollout_depth: int = 3       # Simulation depth
    
    # Verification Parameters
    z3_enabled: bool = True           # Formal verification
    z3_timeout_ms: int = 5000         # Z3 solver timeout
    test_enabled: bool = True         # Run test suite
    test_timeout_s: int = 60          # Test timeout
    
    # Self-Correction Parameters
    max_iterations: int = 5           # Self-correction rounds
    error_threshold: float = 0.8      # Confidence threshold
    
    # Restart Strategy
    restart_enabled: bool = False     # Enable restart on plateau
    restart_threshold: int = 10       # Iterations before restart
    restart_temperature: float = 0.8  # Temperature after restart
    
    # Meta
    config_id: str = ""               # Unique identifier
    source: str = "default"           # How this config was generated
    
    def __post_init__(self):
        if not self.config_id:
            self.config_id = hashlib.md5(
                f"{self.temperature}{self.mcts_iterations}{time.time()}".encode()
            ).hexdigest()[:8]
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "temperature": self.temperature,
            "top_p": self.top_p,
            "max_tokens": self.max_tokens,
            "mcts_iterations": self.mcts_iterations,
            "mcts_exploration": self.mcts_exploration,
            "z3_enabled": self.z3_enabled,
            "test_enabled": self.test_enabled,
            "max_iterations": self.max_iterations,
            "restart_enabled": self.restart_enabled,
            "config_id": self.config_id,
            "source": self.source,
        }
    
    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "SolverConfig":
        return cls(**{k: v for k, v in d.items() if k in cls.__dataclass_fields__})


