class HyperTuner:
    """
    The Hyper-Tuner - Dynamic Configuration Generator.
    
    Combines:
    1. Domain presets (baseline configurations)
    2. Warm-start from history (similar past tasks)
    3. Risk-based adjustment (complexity/risk metrics)
    4. Restart strategy (rugged landscape navigation)
    
    Usage:
        tuner = HyperTuner()
        
        fingerprint = projector.project(problem, code)
        config = tuner.tune(fingerprint)
        
        # Use config for solving
        result = solver.solve(problem, config)
        
        # Record outcome for learning
        tuner.record(fingerprint, config, result.success, result.score)
    """
    
    def __init__(
        self,
        history_path: Optional[str] = None,
        use_warm_start: bool = True,
        use_restart: bool = True,
    ):
        """
        Initialize the Hyper-Tuner.
        
        Args:
            history_path: Path to persist tuning history
            use_warm_start: Enable warm-start from history
            use_restart: Enable restart strategy
        """
        self.history = TuningHistory(history_path)
        self.use_warm_start = use_warm_start
        self.use_restart = use_restart
        
        self.restart_strategy = RestartStrategy()
        
        self.stats = {
            "tunings": 0,
            "warm_starts": 0,
            "restarts": 0,
            "preset_uses": 0,
        }
    
    def tune(
        self,
        fingerprint: TaskFingerprint,
        override: Optional[Dict[str, Any]] = None,
    ) -> SolverConfig:
        """
        Generate optimal configuration for a task.
        
        Args:
            fingerprint: The task fingerprint from projector
            override: Optional manual overrides
            
        Returns:
            SolverConfig optimized for this task
        """
        self.stats["tunings"] += 1
        self.restart_strategy.reset()
        
        # Step 1: Start with domain preset
        base_config = DOMAIN_PRESETS.get(
            fingerprint.primary_domain,
            DOMAIN_PRESETS[TaskDomain.UNKNOWN]
        )
        self.stats["preset_uses"] += 1
        
        # Step 2: Try warm-start from history
        if self.use_warm_start:
            historical = self.history.get_best_config(fingerprint)
            if historical and historical.source != "default":
                base_config = historical
                self.stats["warm_starts"] += 1
                logger.info(f"Warm-start from {historical.source}")
        
        # Step 3: Adjust based on complexity/risk
        config = self._adjust_for_task(base_config, fingerprint)
        
        # Step 4: Apply overrides
        if override:
            config = self._apply_override(config, override)
        
        return config
    
    def _adjust_for_task(
        self,
        config: SolverConfig,
        fingerprint: TaskFingerprint,
    ) -> SolverConfig:
        """Adjust configuration based on task characteristics."""
        # Complexity adjustments
        if fingerprint.complexity_score > 0.7:
            # High complexity: more iterations, deeper search
            mcts_iter = min(500, int(config.mcts_iterations * 1.5))
            max_iter = min(15, config.max_iterations + 2)
        elif fingerprint.complexity_score < 0.3:
            # Low complexity: faster
            mcts_iter = max(5, int(config.mcts_iterations * 0.5))
            max_iter = max(2, config.max_iterations - 1)
        else:
            mcts_iter = config.mcts_iterations
            max_iter = config.max_iterations
        
        # Risk adjustments
        if fingerprint.risk_level > 0.7:
            # High risk: lower temperature, stricter verification
            temp = max(0.1, config.temperature - 0.2)
            z3_enabled = True
            z3_timeout = 15000
        else:
            temp = config.temperature
            z3_enabled = config.z3_enabled
            z3_timeout = config.z3_timeout_ms
        
        # Threading requires restart strategy
        restart = config.restart_enabled or fingerprint.has_threading
        
        return SolverConfig(
            temperature=temp,
            top_p=config.top_p,
            max_tokens=config.max_tokens,
            mcts_iterations=mcts_iter,
            mcts_exploration=config.mcts_exploration,
            mcts_rollout_depth=config.mcts_rollout_depth,
            z3_enabled=z3_enabled,
            z3_timeout_ms=z3_timeout,
            test_enabled=config.test_enabled,
            test_timeout_s=config.test_timeout_s,
            max_iterations=max_iter,
            error_threshold=config.error_threshold,
            restart_enabled=restart,
            restart_threshold=config.restart_threshold,
            source=f"adjusted:{config.source}",
        )
    
    def _apply_override(
        self,
        config: SolverConfig,
        override: Dict[str, Any],
    ) -> SolverConfig:
        """Apply manual overrides to config."""
        config_dict = config.to_dict()
        config_dict.update(override)
        config_dict["source"] = f"override:{config.source}"
        return SolverConfig.from_dict(config_dict)
    
    def check_restart(
        self,
        current_score: float,
        config: SolverConfig,
    ) -> Tuple[bool, SolverConfig]:
        """
        Check if restart should be triggered.
        
        Returns:
            Tuple of (restart_triggered, new_config)
        """
        if not self.use_restart or not config.restart_enabled:
            return False, config
        
        if self.restart_strategy.update(current_score):
            self.stats["restarts"] += 1
            new_config = self.restart_strategy.apply_restart(config)
            return True, new_config
        
        return False, config
    
    def record(
        self,
        fingerprint: TaskFingerprint,
        config: SolverConfig,
        success: bool,
        score: float = 0.0,
        duration_ms: float = 0.0,
        iterations_used: int = 0,
    ) -> None:
        """Record a tuning outcome for learning."""
        fp_hash = hashlib.md5(str(fingerprint.to_dict()).encode()).hexdigest()[:16]
        
        record = TuningRecord(
            task_fingerprint_hash=fp_hash,
            config=config,
            success=success,
            score=score,
            duration_ms=duration_ms,
            iterations_used=iterations_used,
            timestamp=time.time(),
        )
        
        self.history.add(record, fingerprint)
        
        # Auto-save
        if self.history.history_path:
            self.history.save()
    
    def get_stats(self) -> Dict[str, Any]:
        return {
            **self.stats,
            "history": self.history.get_stats(),
        }
    
    def print_stats(self) -> None:
        """Print tuner statistics."""
        stats = self.get_stats()
        print("\n" + "=" * 60)
        print("HYPER-TUNER STATISTICS")
        print("=" * 60)
        print(f"Total Tunings:    {stats['tunings']}")
        print(f"Warm Starts:      {stats['warm_starts']}")
        print(f"Restarts:         {stats['restarts']}")
        print(f"Preset Uses:      {stats['preset_uses']}")
        print(f"History Records:  {stats['history']['total_records']}")
        print("=" * 60)


