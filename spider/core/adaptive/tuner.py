@dataclass
class TuningRecord:
    """Record of a tuning attempt and its outcome."""
    task_fingerprint_hash: str
    config: SolverConfig
    success: bool
    score: float                      # 0.0 to 1.0
    duration_ms: float
    iterations_used: int
    timestamp: float
    
    def to_dict(self) -> Dict:
        return {
            "fingerprint_hash": self.task_fingerprint_hash,
            "config": self.config.to_dict(),
            "success": self.success,
            "score": self.score,
            "duration_ms": self.duration_ms,
            "iterations_used": self.iterations_used,
            "timestamp": self.timestamp,
        }


class TuningHistory:
    """
    Stores and retrieves historical tuning configurations.
    
    From HPO-2 Paper:
    "The core idea is to build a meta-surrogate model that
    learns the mapping from tasks to optimal configurations."
    
    We store successful configurations indexed by task fingerprint
    similarity for warm-start retrieval.
    """
    
    def __init__(self, history_path: Optional[str] = None):
        self.records: List[TuningRecord] = []
        self.history_path = history_path
        
        # Index by domain for fast lookup
        self.domain_index: Dict[TaskDomain, List[TuningRecord]] = defaultdict(list)
        
        # Load if path provided
        if history_path and Path(history_path).exists():
            self.load(history_path)
    
    def add(self, record: TuningRecord, fingerprint: TaskFingerprint) -> None:
        """Add a tuning record to history."""
        self.records.append(record)
        self.domain_index[fingerprint.primary_domain].append(record)
        
        # Keep only last 1000 records
        if len(self.records) > 1000:
            self.records = self.records[-1000:]
    
    def find_similar(
        self,
        fingerprint: TaskFingerprint,
        top_k: int = 5,
    ) -> List[Tuple[TuningRecord, float]]:
        """
        Find similar past configurations.
        
        Uses domain matching and fingerprint similarity.
        """
        # First, get records from same domain
        candidates = self.domain_index.get(fingerprint.primary_domain, [])
        
        if not candidates:
            # Fall back to all records
            candidates = self.records
        
        # Score by success and recency
        scored = []
        for record in candidates:
            # Success bonus
            score = 1.0 if record.success else 0.3
            # Recency bonus (decay over 24 hours)
            age_hours = (time.time() - record.timestamp) / 3600
            recency_bonus = math.exp(-age_hours / 24)
            score *= (0.5 + 0.5 * recency_bonus)
            
            scored.append((record, score))
        
        # Sort by score
        scored.sort(key=lambda x: x[1], reverse=True)
        return scored[:top_k]
    
    def get_best_config(
        self,
        fingerprint: TaskFingerprint,
    ) -> Optional[SolverConfig]:
        """Get the best historical config for a similar task."""
        similar = self.find_similar(fingerprint, top_k=1)
        if similar:
            return similar[0][0].config
        return None
    
    def save(self, path: Optional[str] = None) -> None:
        """Save history to disk."""
        path = path or self.history_path
        if not path:
            return
        
        data = [r.to_dict() for r in self.records]
        with open(path, 'w') as f:
            json.dump(data, f, indent=2)
    
    def load(self, path: str) -> None:
        """Load history from disk."""
        try:
            with open(path, 'r') as f:
                data = json.load(f)
            
            for item in data:
                record = TuningRecord(
                    task_fingerprint_hash=item["fingerprint_hash"],
                    config=SolverConfig.from_dict(item["config"]),
                    success=item["success"],
                    score=item["score"],
                    duration_ms=item["duration_ms"],
                    iterations_used=item["iterations_used"],
                    timestamp=item["timestamp"],
                )
                self.records.append(record)
        except (json.JSONDecodeError, KeyError) as e:
            logger.warning(f"Failed to load tuning history: {e}")
    
    def get_stats(self) -> Dict[str, Any]:
        if not self.records:
            return {"total_records": 0}
        
        success_count = sum(1 for r in self.records if r.success)
        return {
            "total_records": len(self.records),
            "success_rate": success_count / len(self.records),
            "domains": {d.name: len(recs) for d, recs in self.domain_index.items()},
        }


